"""Shared rendering primitives for the studio code generator.

Everything here exists so no layer invents its own spelling: one line buffer with
one indentation rule, one naming rule, one logical-type-to-text rule, one literal
rule, one import collector and one syntax gate. Layers (``tables``, ``projections``,
``topology``, ``bindings``, ``sources``, ``annotations``, ``entry``) compose these
into :class:`RenderedFile` values, which ``project`` writes.

Two deliberate choices:

* Naming mirrors ``kg_build_system._support.naming`` rather than importing it. That
  module is private by its leading underscore, so it is not a surface studio may
  depend on; the functions below restate its rules, and
  ``tests/test_generate.py`` asserts the two implementations agree, which is what
  keeps an external name written by studio identical to the one the framework
  would infer from the same declaration.
* Imports are derived from what a file actually annotates. The framework's own
  generator imports the whole representative set unconditionally; studio names
  only the types in play, because generated files are meant to be read in a diff.
"""

from __future__ import annotations

import hashlib
import json
import keyword
import re
import textwrap
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Final

import libcst as cst
from kg_build_system.expressions import literal as infer_literal
from kg_build_system.types import ArrayType as KgArrayType
from kg_build_system.types import NullableType as KgNullableType
from kg_build_system.types import UnitType as KgUnitType

from ..ir.document import ArrayType, LogicalType, NullableType, ProjectDocument
from ..ir.document import StructType, UnitType, unwrap_nullable

INDENT: Final = "    "

#: Every generated file carries this first line, then the IR refs it came from.
GENERATED_HEADER: Final = "# Generated by kg-studio. Do not edit manually."

#: The framework's generated-file directives: the rendering is written for humans,
#: so formatters and unused-import linting are switched off file-wide.
FILE_DIRECTIVES: Final = (
    "# fmt: off",
    "# isort: skip_file",
    "# ruff: noqa: F401",
    "# pyright: reportUnusedImport=false",
)

_STDLIB_MODULES: Final = frozenset({"dataclasses", "pathlib", "typing"})

#: The canonical units an annotation spells with a representative class rather than
#: with a builtin, because the representative is the class of the value itself.
REPRESENTATIVE_TYPES: Final = {
    "date": "Date",
    "time": "Time",
    "timestamp": "Timestamp",
    "uuid": "Uuid",
}

#: The unit singletons used when an explicit logical type has to be spelled out.
UNIT_SINGLETONS: Final = {
    "bool": "BOOL",
    "int": "INT",
    "float": "FLOAT",
    "str": "STR",
    "date": "DATE",
    "time": "TIME",
    "timestamp": "TIMESTAMP",
    "uuid": "UUID",
}


class GenerationError(Exception):
    """Rendering refused: the document cannot be turned into honest Python."""


# --------------------------------------------------------------------- line buffer


class Lines:
    """A deterministic line buffer.

    ``level`` multiplies :data:`INDENT`, so nesting is arithmetic rather than
    string concatenation and cannot drift between two renderings of one document.
    """

    __slots__ = ("_items",)

    def __init__(self, items: Sequence[str] = ()) -> None:
        self._items: list[str] = list(items)

    @property
    def items(self) -> tuple[str, ...]:
        return tuple(self._items)

    def add(self, text: str = "", *, level: int = 0) -> Lines:
        self._items.append(f"{INDENT * level}{text}" if text else "")
        return self

    def extend(self, texts: Iterable[str] | "Lines") -> Lines:
        self._items.extend(texts.items if isinstance(texts, Lines) else texts)
        return self

    def blank(self) -> Lines:
        self._items.append("")
        return self

    def __bool__(self) -> bool:
        return bool(self._items)

    def __len__(self) -> int:
        return len(self._items)

    def render(self) -> str:
        """The buffer as a file body: no trailing blank lines, one final newline."""
        items = list(self._items)
        while items and not items[-1]:
            items.pop()
        return "".join(f"{item}\n" for item in items)


# -------------------------------------------------------------------------- naming


def snake_case(value: str) -> str:
    """``CamelCase``/``mixed digits`` to ``snake_case``, as the framework spells it."""
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"([A-Za-z])([0-9])", r"\1_\2", value)
    value = re.sub(r"([0-9])([A-Za-z])", r"\1_\2", value)
    return value.lower()


def declaration_name(class_name: str, *, suffixes: Sequence[str] = ()) -> str:
    """The logical name a class carries, minus one matching declaration suffix."""
    stem = class_name
    for suffix in suffixes:
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
            break
    if not stem:
        raise GenerationError(f"{class_name!r} has no name after its declaration suffix")
    return snake_case(stem)


def python_name(value: str) -> str:
    """Any IR label or id as a valid lowercase Python identifier."""
    cleaned = re.sub(r"[^0-9a-zA-Z_]+", "_", value.strip()).strip("_").lower()
    cleaned = re.sub(r"_+", "_", cleaned)
    if not cleaned:
        raise GenerationError(f"{value!r} has no usable Python name")
    if cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    if keyword.iskeyword(cleaned):
        cleaned = f"{cleaned}_"
    return cleaned


def member_name(name: str) -> str:
    """The attribute one IR member is declared with.

    ``options`` is the framework's reserved class-level value, so a member that
    would claim it keeps the escape hatch the framework itself uses: the attribute
    is ``options_`` while ``field(name='options')`` still carries the real name.
    """
    attribute = python_name(name)
    return f"{attribute}_" if attribute == "options" else attribute


# -------------------------------------------------------------------- type text


class Imports:
    """The named imports of one file, gathered as they are used.

    Rendering sorts them into the three groups the reference project uses — the
    standard library, the framework, then this project's own packages — and one
    sorted ``from … import …`` line per module, so the same document always yields
    the same bytes.
    """

    def __init__(self, package: str, own_module: str = "") -> None:
        self._package = package
        #: A file never imports from itself; declaring modules live beside it.
        self._own_module = own_module
        self._modules: dict[str, set[str]] = {}

    def add(self, module: str, *names: str) -> None:
        if not names or module == self._own_module:
            return
        if not module:
            raise GenerationError(
                f"cannot import {', '.join(sorted(names))} from an unnamed module: a struct "
                "reference must name the module that declares it"
            )
        self._modules.setdefault(module, set()).update(names)

    def names(self) -> tuple[str, ...]:
        """Every name this file will bind, so a generated variable cannot shadow one."""
        return tuple(sorted({name for names in self._modules.values() for name in names}))

    def add_framework(self, *names: str) -> None:
        self.add("kg_build_system", *names)

    def add_type(self, name: str) -> None:
        self.add("kg_build_system.types", name)

    def representative(self, unit: str) -> str:
        """The annotation spelling of one canonical unit, importing it when needed."""
        builtin = {"bool": "bool", "int": "int", "float": "float", "str": "str"}
        if unit in builtin:
            return builtin[unit]
        name = REPRESENTATIVE_TYPES[unit]
        self.add_type(name)
        return name

    def array(self) -> str:
        self.add_type("Array")
        return "Array"

    def singleton(self, unit: str) -> str:
        """The framework's unit singleton, for an explicit ``logical_type=`` argument."""
        name = UNIT_SINGLETONS[unit]
        self.add_type(name)
        return name

    def struct(self, reference: StructType, *, current_module: str) -> str:
        """The class name for a struct reference, importing it from its own module."""
        if reference.module != current_module:
            self.add(reference.module, reference.qualname.split(".")[-1])
        return reference.qualname.split(".")[-1]

    def block(self) -> list[str]:
        """The import lines, grouped and sorted."""

        def rank(module: str) -> tuple[int, str]:
            if module in _STDLIB_MODULES:
                return (0, module)
            if module == self._package or module.startswith(f"{self._package}."):
                return (2, module)
            return (1, module)

        lines: list[str] = []
        groups: list[list[str]] = []
        for module, names in sorted(self._modules.items(), key=lambda item: rank(item[0])):
            group = rank(module)[0]
            while len(groups) <= group:
                groups.append([])
            groups[group].extend(self._lines(module, sorted(names)))
        for group in groups:
            if not group:
                continue
            # One blank between groups, none before the first, whatever is absent.
            if lines:
                lines.append("")
            lines.extend(group)
        return lines

    @staticmethod
    def _lines(module: str, names: Sequence[str]) -> list[str]:
        """One import statement, hung like the reference project's long ones."""
        head = f"from {module} import "
        flat = head + ", ".join(names)
        if len(flat) <= IMPORT_WIDTH:
            return [flat]
        return [head + "(", *(f"{INDENT}{name}," for name in names), ")"]


def annotation_text(value: LogicalType, imports: Imports, *, current_module: str) -> str:
    """The annotation text for one logical type inside ``current_module``.

    Nullable is written as PEP 604 ``T | None``, which is what the framework
    normalizes back to ``NullableType``; arrays and structs take their
    representative names, imported exactly when they appear.
    """
    if isinstance(value, NullableType):
        return f"{annotation_text(value.value, imports, current_module=current_module)} | None"
    if isinstance(value, ArrayType):
        return f"{imports.array()}[{annotation_text(value.item, imports, current_module=current_module)}]"
    if isinstance(value, StructType):
        return imports.struct(value, current_module=current_module)
    if isinstance(value, UnitType):
        return imports.representative(value.name)
    raise GenerationError(f"unsupported logical type {value!r}")


def framework_type(value: LogicalType) -> Any:
    """The ``kg_build_system.types`` object studio's logical type stands for."""
    if isinstance(value, NullableType):
        return KgNullableType(framework_type(value.value))
    if isinstance(value, ArrayType):
        return KgArrayType(framework_type(value.item))
    if isinstance(value, UnitType):
        return KgUnitType(value.name)
    raise GenerationError(f"no framework type for {value!r}")


def type_object_text(value: LogicalType, imports: Imports) -> str:
    """Constructor text for an explicit ``logical_type=`` argument.

    The framework's own names are used (``NullableType(STR)``, ``ArrayType(…)``)
    rather than strings, per the authoring contract.
    """
    if isinstance(value, NullableType):
        imports.add_type("NullableType")
        return f"NullableType({type_object_text(value.value, imports)})"
    if isinstance(value, ArrayType):
        imports.add_type("ArrayType")
        return f"ArrayType({type_object_text(value.item, imports)})"
    if isinstance(value, UnitType):
        return imports.singleton(value.name)
    raise GenerationError(f"no literal logical type for {value!r}")


# ----------------------------------------------------------------------- literals
#
# Two spellings of the same string, because two idioms are being mirrored. The data
# contracts copy the framework's own generated files, which write ``field(name='x')``;
# everything an author would have typed by hand — ``default_to("Unnamed site")``,
# ``layout="{group_path}/{table_name}.json"`` — copies ``reference_project``, where the
# convention is double quotes.


def string_literal(text: str) -> str:
    """A generated-file string literal: single quotes, as ``repr`` spells them."""
    return repr(text)


def text_literal(text: str) -> str:
    """An authored-file string literal: double quotes, as the reference project does."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


#: The canonical units whose value is carried as text in the document and rebuilt in
#: code by the representative class the framework's ``literal`` demands. A ``Uuid`` is
#: constructed directly; the ``datetime`` aliases go through ``fromisoformat``, which is
#: total for the canonical form ``canonical_value_text`` produced.
_CANONICAL_CALLS: Final = {
    "date": "Date.fromisoformat",
    "time": "Time.fromisoformat",
    "timestamp": "Timestamp.fromisoformat",
    "uuid": "Uuid",
}


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise GenerationError(message)


def _python_value(value: Any, logical_type: LogicalType) -> Any:
    """The Python value one frozen IR literal stands for."""
    base = unwrap_nullable(logical_type)
    if value is None:
        _require(
            isinstance(logical_type, NullableType),
            "a null literal needs a nullable logical type to stand for",
        )
        return None
    if isinstance(base, ArrayType):
        _require(isinstance(value, list), f"array literal expected, got {value!r}")
        return [_python_value(item, base.item) for item in value]
    if isinstance(base, StructType):
        raise GenerationError("a literal cannot embed a struct value")
    if isinstance(base, UnitType):
        if base.name == "float":
            _require(
                not isinstance(value, bool) and isinstance(value, (int, float)),
                f"float literal expected, got {value!r}",
            )
            return float(value)
        if base.name == "int":
            _require(
                not isinstance(value, bool) and isinstance(value, int),
                f"integer literal expected, got {value!r}",
            )
            return int(value)
        if base.name == "bool":
            _require(isinstance(value, bool), f"boolean literal expected, got {value!r}")
            return value
        if base.name == "str":
            _require(isinstance(value, str), f"string literal expected, got {value!r}")
            return value
        _require(
            isinstance(value, str), f"{base.name} literal must be carried as canonical text"
        )
        return _BUILDERS[base.name](value)
    raise GenerationError(f"unsupported literal type {logical_type!r}")


def _build_date(text: str) -> Any:
    from datetime import date

    return date.fromisoformat(text)


def _build_time(text: str) -> Any:
    from datetime import time

    return time.fromisoformat(text)


def _build_timestamp(text: str) -> Any:
    from datetime import datetime

    return datetime.fromisoformat(text)


def _build_uuid(text: str) -> Any:
    from uuid import UUID

    return UUID(text)


_BUILDERS: Final = {
    "date": _build_date,
    "time": _build_time,
    "timestamp": _build_timestamp,
    "uuid": _build_uuid,
}


def literal_value_text(
    value: Any, logical_type: LogicalType, imports: Imports, *, authored: bool = True
) -> str:
    """The Python text for one literal value, with no type argument around it.

    ``authored`` picks the quoting idiom: expression stacks and ``bind_source``
    arguments take double quotes, a contract declaration takes single.
    """
    quote = text_literal if authored else string_literal
    base = unwrap_nullable(logical_type)
    if value is None:
        _require(isinstance(logical_type, NullableType), "a null literal needs a nullable type")
        return "None"
    if isinstance(base, ArrayType):
        _require(isinstance(value, list), f"array literal expected, got {value!r}")
        items = [literal_value_text(item, base.item, imports, authored=authored) for item in value]
        return "[" + ", ".join(items) + "]"
    if isinstance(base, UnitType):
        if base.name in _CANONICAL_CALLS:
            _require(
                isinstance(value, str), f"{base.name} literal must be carried as canonical text"
            )
            representative = imports.representative(base.name)
            call = representative if base.name == "uuid" else f"{representative}.fromisoformat"
            return f"{call}({quote(value)})"
        if base.name == "float":
            _require(
                not isinstance(value, bool) and isinstance(value, (int, float)),
                f"float literal expected, got {value!r}",
            )
            return repr(float(value))
        if base.name == "int":
            _require(
                not isinstance(value, bool) and isinstance(value, int),
                f"integer literal expected, got {value!r}",
            )
            return repr(int(value))
        if base.name == "bool":
            _require(isinstance(value, bool), f"boolean literal expected, got {value!r}")
            return repr(value)
        if base.name == "str":
            _require(isinstance(value, str), f"string literal expected, got {value!r}")
            return quote(value)
    raise GenerationError(f"unsupported literal type {logical_type!r}")


def literal_is_inferable(value: Any, logical_type: LogicalType) -> bool:
    """Whether ``value_expression(x)`` alone re-infers exactly this logical type.

    Asked of the framework's own ``literal`` so the answer cannot drift from the
    inference rule: a null, an empty or all-null array, and a JSON integer standing for
    a float need the explicit type argument; nothing else does.
    """
    try:
        python_value = _python_value(value, logical_type)
        return infer_literal(python_value).logical_type == framework_type(logical_type)
    except (GenerationError, TypeError):
        return False


def literal_expression_text(
    value: Any, logical_type: LogicalType, imports: Imports, *, authored: bool = True
) -> str:
    """``value_expression(...)`` for one IR literal, typed only where it must be."""
    imports.add_framework("value_expression")
    text = literal_value_text(value, logical_type, imports, authored=authored)
    if literal_is_inferable(value, logical_type):
        return f"value_expression({text})"
    return f"value_expression({text}, logical_type={type_object_text(logical_type, imports)})"


def scalar_argument_text(
    value: Any, logical_type: LogicalType, imports: Imports
) -> str | None:
    """The plain-Python argument for a value-taking authoring method, or ``None``.

    ``default_to("Unnamed site")`` and ``add(1)`` are what an author writes, and the
    framework coerces a plain value to a literal of the operand's type; a null or an
    array has no plain spelling that survives the framework's inference, so the caller
    falls back to :func:`literal_expression_text`.
    """
    base = unwrap_nullable(logical_type)
    if isinstance(base, UnitType) and not isinstance(logical_type, NullableType):
        return literal_value_text(value, logical_type, imports)
    if isinstance(base, ArrayType) and isinstance(value, list) and value:
        if base.item == UnitType(name="str") and all(isinstance(item, str) for item in value):
            return literal_value_text(value, logical_type, imports)
    return None


def literal_arguments(values: Mapping[str, Any], *, order: Sequence[str] | None = None) -> list[str]:
    """``name=value`` arguments from JSON scalars, in the order the declaring type gives."""
    keys = list(order) if order is not None else sorted(values)
    keys.extend(sorted(key for key in values if key not in keys))
    return [f"{key}={argument_text(values[key])}" for key in keys if key in values]


def argument_text(value: Any) -> str:
    """A JSON scalar or container as authored Python source."""
    if isinstance(value, str):
        return text_literal(value)
    if isinstance(value, bool) or value is None or isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(argument_text(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{argument_text(key)}: {argument_text(item)}" for key, item in sorted(value.items())) + "}"
    raise GenerationError(f"cannot render {value!r} as an argument")


# ---------------------------------------------------------------------- documents


def document_fingerprint(document: ProjectDocument) -> str:
    """Identity of everything the generated code is made from.

    ``revision`` and canvas ``views`` deliberately stay out: neither changes one
    byte of Python, so an edit that only moves a node must not invalidate the
    anchor index the diagnostics module is holding.
    """
    payload = document.model_dump(mode="json", exclude={"revision", "views"})
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return f"sha256:{hashlib.sha256(encoded).hexdigest()}"


def validate_source(text: str, *, path: str) -> None:
    """Refuse to emit Python that does not parse, as one clear error."""
    try:
        cst.parse_module(text)
    except cst.ParserSyntaxError as error:
        raise GenerationError(f"{path}: rendered source does not parse: {error}") from None


# --------------------------------------------------------------- rendered artifacts


@dataclass(frozen=True)
class AnchorHint:
    """What one rendered construct is, so the anchor index can label it.

    ``name`` is the class name for a declaration, the module-level target for an
    assignment, or ``"Class.attribute"`` for a member. ``keyword`` locates one
    keyword argument inside the call that ``name``'s assignment builds.
    """

    kind: str
    ref: str
    name: str
    keyword: str | None = None


@dataclass(frozen=True)
class RenderedFile:
    """One owned project file, already validated."""

    path: str
    module: str
    content: str
    owner_ref: str
    anchors: tuple[AnchorHint, ...] = ()


def generated_file(
    *,
    path: str,
    module: str,
    docstring: str | None,
    imports: Imports,
    body: Lines | Sequence[str],
    owner_refs: Sequence[str],
    anchors: Sequence[AnchorHint] = (),
    directives: bool = False,
) -> RenderedFile:
    """Assemble one file from its docstring, imports and body, then validate it."""
    lines = Lines()
    lines.extend(generated_header(owner_refs, directives=directives))
    if docstring:
        lines.extend(docstring_lines(docstring))
        lines.blank()
    lines.extend(imports.block())
    body_lines = normalize_body(body.items if isinstance(body, Lines) else body)
    if body_lines:
        lines.blank()
        lines.blank()
        lines.extend(body_lines)
    content = lines.render()
    validate_source(content, path=path)
    return RenderedFile(
        path=path,
        module=module,
        content=content,
        owner_ref=owner_refs[0] if owner_refs else "",
        anchors=tuple(anchors),
    )


MAX_TOP_BLANKS: Final = 2
MAX_INNER_BLANKS: Final = 1


def normalize_body(lines: Sequence[str]) -> list[str]:
    """Blank lines as Python style wants them, whatever the layers appended.

    Two blank lines before a top-level statement, one inside a suite, none where the
    renderer asked for none: each layer appends a trailing blank after its
    declaration, so the count is a property of the finished file rather than of how
    many pieces it was built from — which is what keeps a rendering byte-stable.
    """
    out: list[str] = []
    blanks = 0
    for line in lines:
        if not line.strip():
            blanks += 1
            continue
        if blanks and out:
            top = not line[:1].isspace()
            out.extend([""] * (MAX_TOP_BLANKS if top else MAX_INNER_BLANKS))
        blanks = 0
        out.append(line)
    return out


def generated_header(refs: Sequence[str], *, directives: bool = False) -> list[str]:
    """The framework's generated-file header idiom, with the IR refs appended."""
    lines = [GENERATED_HEADER, *(f"# ir: {value}" for value in refs)]
    if directives:
        lines.extend(FILE_DIRECTIVES)
    lines.append("")
    return lines


def _docstring_body(text: str) -> str:
    """Descriptions as prose: whitespace normalised, paragraph breaks kept, escaped."""
    paragraphs = [ " ".join(item.split()) for item in text.strip().split("\n\n") ]
    body = "\n\n".join(item for item in paragraphs if item)
    return body.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


DOCSTRING_WIDTH: Final = 88
IMPORT_WIDTH: Final = 88


def docstring_lines(text: str, *, level: int = 0) -> list[str]:
    """A class- or module-level docstring, paragraphs kept, lines wrapped to width."""
    prefix = INDENT * level
    body = _docstring_body(text)
    if not body:
        return []
    width = max(24, DOCSTRING_WIDTH - len(prefix) - 4)
    paragraphs = [textwrap.wrap(item, width=width) or [""] for item in body.split("\n\n")]
    if len(paragraphs) == 1 and len(paragraphs[0]) == 1:
        return [f'{prefix}"""{paragraphs[0][0]}"""']
    lines = [f'{prefix}"""{paragraphs[0][0]}', *(f"{prefix}{line}" for line in paragraphs[0][1:])]
    for paragraph in paragraphs[1:]:
        lines.append("")
        lines.extend(f"{prefix}{line}" for line in paragraph)
    lines.append(f'{prefix}"""')
    return lines


def attribute_docstring_lines(text: str, *, level: int = 1) -> list[str]:
    """The documentation written directly below a field or property declaration.

    One line, because the framework attaches a literal to the member above it: a
    wrapped attribute docstring would be read as a docstring of its own.
    """
    body = " ".join(_docstring_body(text).split())
    return [] if not body else [f'{INDENT * level}"""{body}"""']


def literal_arguments(values: Mapping[str, Any], *, order: Sequence[str] | None = None) -> list[str]:
    """``name=value`` arguments built from JSON scalars, in a stable order."""
    keys = list(order) if order is not None else sorted(values)
    keys.extend(sorted(key for key in values if key not in keys))
    return [f"{key}={values[key]!r}" for key in keys if key in values]


def module_path(package: str, parts: Sequence[str]) -> str:
    """The dotted module a sequence of package segments names."""
    return ".".join((package, *parts))
