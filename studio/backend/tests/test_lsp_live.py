CITY_LINE_1BASED = BINDING_WITH_ERROR.splitlines().index("        city=3,") + 1


def anchors_json() -> str:
    """A hand-authored anchor index for the fixture, in the agreed format.

    The generator is written in parallel, so the diagnostics subsystem is tested
    against this instead of against its output; the ranges are computed from the file
    text above so they cannot drift.
    """
    call_start = BINDING_WITH_ERROR.splitlines().index("site_binding = node_binding(") + 1
    file_end = len(BINDING_WITH_ERROR.splitlines())
    return json.dumps(
        {
            "format_version": 1,
            "revision": 1,
            "document_fingerprint": "sha256-live-probe",
            "files": {
                BINDING_FILE: [
                    {
                        "ref": "binding:site_binding",
                        "line": call_start,
                        "end_line": file_end,
                        "column": 1,
                        "end_column": 2,
                        "node": "call",
                    },
                    {
                        "ref": "binding:site_binding.property.city",
                        "line": CITY_LINE_1BASED,
                        "end_line": CITY_LINE_1BASED,
                        "column": 9,
                        "end_column": 17,
                        "node": "keyword",
                    },
                    {
                        "ref": "binding:site_binding",
                        "line": 1,
                        "end_line": file_end + 1,
                        "column": 1,
                        "end_column": 1,
                        "node": "file",
                    },
                ]
            },
        },
        indent=2,
    )


