def test_pyright_publishes_the_rule_and_the_position(
    project: Path, framework_venv: Path
) -> None:
    received: list[Notification] = []
    client = LanguageServerClient(
        discover_server_command(framework_venv),
        project,
        initialization_options={"typeCheckingMode": "basic"},
        on_notification=received.append,
        request_timeout=60.0,
    )
    client.start()
    try:
        assert client.ready
        # Verified: pyright advertises incremental sync and accepts whole-document
        # change events anyway, which is what ``change_file`` sends.
        assert client.server_capabilities.get("textDocumentSync") in (1, 2)

        binding_path = project / BINDING_FILE
        uri = client.open_file(binding_path)
        assert client.open_documents == (uri,)
        assert path_to_uri(binding_path) == uri

        publish = wait_for(lambda: published(received, uri))
        assert publish is not None, "pyright never published diagnostics for the opened file"
        diagnostics = publish.params["diagnostics"]

        # If the framework did not resolve, every file would be full of these.
        assert not [item for item in diagnostics if item.get("code") == "reportMissingImports"], [
            item["message"] for item in diagnostics if item.get("code") == "reportMissingImports"
        ]

        argument_errors = [item for item in diagnostics if item.get("code") == "reportArgumentType"]
        assert argument_errors, [item.get("code") for item in diagnostics]
        error = argument_errors[0]
        assert error["severity"] == 1, "a type error must arrive as LSP severity 1"
        assert error["source"] == "Pyright"
        assert 'parameter "city"' in error["message"]
        # The rule lives in ``code``; ``data`` is absent unless pyright has actions
        # or an "unnecessary" mark to attach, which is why reading ``data.rule``
        # alone would have found nothing here.
        assert "data" not in error or "rule" not in (error.get("data") or {})
        assert error["range"]["start"] == {"line": ERROR_LINE_0BASED, "character": ERROR_CHARACTER_0BASED}
        assert error["range"]["end"] == {"line": ERROR_LINE_0BASED, "character": ERROR_CHARACTER_0BASED + 1}
        # The server echoes the buffer version it diagnosed.
        assert publish.params.get("version") == 1

        # Regeneration path: the file on disk is fixed and the buffer reopened, so the
        # diagnostic must disappear rather than linger.
        received.clear()
        binding_path.write_text(BINDING_CLEAN, encoding="utf-8")
        client.reopen([binding_path])
        assert wait_for(lambda: published(received, uri, clean=True)) is not None, (
            "the reopened buffer never republished as clean"
        )
    finally:
        client.stop(timeout=10.0)
    assert not client.alive
    assert client.process_id is None


def test_the_service_maps_the_diagnostic_onto_its_ir_ref(
    project: Path, framework_venv: Path
) -> None:
    snapshots: list[int] = []
    service = DiagnosticsService(
        project,
        PACKAGE,
        framework_venv=framework_venv,
        document_provider=lambda: DOCUMENT,
        debounce_seconds=0.25,
    )
    unsubscribe = service.subscribe(lambda problems: snapshots.append(len(problems)))
    service.start()
    try:
        assert service.state == "ready", service.state_message
        assert service.files_open == len(service.owned_files()) == 8

        arrived = wait_for(lambda: [item for item in service.snapshot() if item.tier == "types"])
        assert arrived is not None, f"no type problems arrived (state={service.state})"

        assert not [item for item in service.snapshot() if item.code == "reportMissingImports"], [
            item.message for item in service.snapshot() if item.code == "reportMissingImports"
        ]

        binding_problems = [item for item in service.snapshot() if item.file == BINDING_FILE]
        assert binding_problems, [item.file for item in service.snapshot()]
        problem = next(item for item in binding_problems if item.code == "reportArgumentType")

        assert problem.tier == "types"
        assert problem.severity == "error"
        assert problem.code == "reportArgumentType"
        # Positions are handed to the UI 1-based, as the contract requires.
        assert problem.line == ERROR_LINE_0BASED + 1
        assert problem.column == ERROR_CHARACTER_0BASED + 1
        assert problem.end_line == ERROR_LINE_0BASED + 1
        assert problem.end_column == ERROR_CHARACTER_0BASED + 2
        # The position falls inside the fixture's ``city`` keyword range, so this is a
        # real anchor hit rather than a name match or the file's owner.
        assert problem.ref == "binding:site_binding.property.city"
        assert problem.ref_trusted == "anchor"
        assert problem.hint and problem.hint != problem.message
        assert "city" in problem.hint
        assert len(problem.id) == 40

        status = service.status()
        assert status["state"] == "ready"
        assert status["errors"] >= 1

        # Debounce: a burst of per-file publishes must settle into silence rather than
        # emit one snapshot per file.
        wait_for(lambda: snapshots)
        time.sleep(1.5)
        settled = len(snapshots)
        time.sleep(1.0)
        assert len(snapshots) == settled, "the service is publishing without a change"
        assert settled < service.files_open, (
            f"{settled} snapshots for {service.files_open} files means no coalescing"
        )

        # Regeneration: fix the file, tell the service, and the problem must go away.
        (project / BINDING_FILE).write_text(BINDING_CLEAN, encoding="utf-8")
        service.reopen([BINDING_FILE])
        cleared = wait_for(lambda: not [item for item in service.snapshot() if item.code == "reportArgumentType"])
        assert cleared, "the regenerated buffer never republished clean through the service"
        assert service.state == "ready", service.state_message
    finally:
        unsubscribe()
        service.stop(timeout=10.0)
    assert not service._client, "stopping must drop the server"  # noqa: SLF001 - teardown check


def test_a_missing_server_is_reported_not_raised(tmp_path: Path) -> None:
    root = tmp_path / "empty"
    (root / PACKAGE).mkdir(parents=True)
    service = DiagnosticsService(root, PACKAGE, server_command=[str(root / "no-such-language-server")])
    service.start()
    try:
        assert service.state == "error"
        assert service.state_message
        assert service.snapshot() == []
        assert service.status()["state"] == "error"
    finally:
        service.stop(timeout=2.0)
