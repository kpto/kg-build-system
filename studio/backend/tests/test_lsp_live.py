@pytest.fixture(scope="module")
def framework_venv() -> Path:
    """The environment pyright must resolve ``kg_build_system`` from.

    Skipped rather than failed when pyright is not installed: this suite is the only
    place the real server runs, and a missing dev dependency is not a regression.
    """
    try:
        venv = discover_framework_venv()
        discover_server_command(venv)
    except DiagnosticsError as error:
        pytest.skip(str(error))
    return venv


@pytest.fixture
def project(tmp_path: Path, framework_venv: Path) -> Path:
    """A tiny generated-looking project, its config, and its anchor index."""
    root = tmp_path / "estate"
    (root / PACKAGE / "table" / "sites").mkdir(parents=True)
    (root / PACKAGE / "topology").mkdir(parents=True)
    (root / PACKAGE / "bindings" / "site").mkdir(parents=True)
    for directory in ("", "table", "topology", "bindings"):
        (root / PACKAGE / directory / "__init__.py").write_text("", encoding="utf-8")
    (root / PACKAGE / "table" / "sites" / "__init__.py").write_text(SITES_TABLE, encoding="utf-8")
    (root / PACKAGE / "topology" / "common.py").write_text(TOPOLOGY_COMMON, encoding="utf-8")
    (root / PACKAGE / "topology" / "site.py").write_text(TOPOLOGY_SITE, encoding="utf-8")
    (root / PACKAGE / "bindings" / "site" / "__init__.py").write_text(BINDING_WITH_ERROR, encoding="utf-8")
    anchors = root / ANCHORS_RELATIVE_PATH
    anchors.parent.mkdir(parents=True, exist_ok=True)
    anchors.write_text(anchors_json(), encoding="utf-8")
    write_pyright_config(root, PACKAGE, framework_venv=framework_venv)
    return root


def wait_for(predicate, timeout: float = 120.0, interval: float = 0.2):
    """Poll until ``predicate`` returns something truthy; pyright's first pass is slow."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        value = predicate()
        if value:
            return value
        time.sleep(interval)
    return None


def published(received: list[Notification], uri: str, *, clean: bool = False) -> Notification | None:
    for item in received:
        if item.method != "textDocument/publishDiagnostics" or item.params.get("uri") != uri:
            continue
        diagnostics = item.params.get("diagnostics") or []
        if bool(diagnostics) != clean:
            return item
    return None


# ------------------------------------------------------------- the written config


def test_the_written_config_is_the_one_that_resolves_the_framework(
    project: Path, framework_venv: Path
) -> None:
    config = json.loads((project / "pyrightconfig.json").read_text(encoding="utf-8"))
    assert config["include"] == [PACKAGE]
    assert config["typeCheckingMode"] == "basic"
    assert config["strict"] == [PACKAGE]
    assert config["reportMissingTypeStubs"] is False
    # Verified against pyright 1.1.411: this pair is what makes ``import
    # kg_build_system`` resolve in a generated project. ``pythonPath`` is rejected by
    # the config parser outright, and ``--pythonpath`` is ignored by the language
    # server, so neither is an option here.
    assert config["venvPath"] == str(framework_venv.parent)
    assert config["venv"] == framework_venv.name
    assert config["pythonVersion"] == detect_python_version(framework_venv)
    assert "pythonPath" not in config


def test_the_discovered_server_is_pyright(framework_venv: Path) -> None:
    command = discover_server_command(framework_venv)
    assert command[-1] == "--stdio"
    assert "pyright-langserver" in Path(command[0]).name


