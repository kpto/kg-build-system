"""Integration: the real ``pyright-langserver`` against a generated-looking project.

This is the test that decides whether the rest of the subsystem is honest. pyright's
wire behaviour, its config handling and its resolution of ``kg_build_system`` are
verified here by running it:

* the project is a miniature of what ``generate`` writes — a table package, a topology
  package, a binding module — under a temporary project root;
* ``pyrightconfig.json`` is the one :mod:`studio_backend.diagnostics.service` writes,
  so a regression in ``venvPath`` handling shows up here as ``reportMissingImports``
  instead of as a type tier full of noise in production;
* the deliberate error is a real type error inside the framework's own API, which an
  unresolved ``kg_build_system`` could not produce at all.

The expected rule and position were established by running pyright 1.1.411 against
exactly this fixture, and the assertions name the numbers: LSP line 14/character 13,
i.e. the ``3`` in ``city=3``, which the contract publishes 1-based as 15:14.
"""

