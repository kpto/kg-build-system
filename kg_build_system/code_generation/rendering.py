"""Deterministic rendering and validation of normalized generated packages."""

from __future__ import annotations

from hashlib import sha256
import json
from pathlib import Path, PurePosixPath
from typing import Any, Final
import libcst as cst

from .models import (
    DiscoveredGeneration,
    GeneratedArrayType,
    GeneratedClass,
    GeneratedField,
    GeneratedFile,
    GeneratedNullableType,
    GeneratedPackage,
    GeneratedScalarType,
    GeneratedStructType,
    GeneratedType,
    GenerationError,
    NullabilityNote,
)

FORMAT_VERSION = "5"
HEADER = "# Generated by kg-build-system. Do not edit manually."

#: The directives every generated file carries. The rendering is not what
#: ``black``/``isort`` would write, and the representative import below names the
#: whole set whatever a file happens to annotate, so an un-accessed name there is
#: the design rather than a finding for a linter to report.
FILE_DIRECTIVES: Final = (
    "# fmt: off",
    "# isort: skip_file",
    "# ruff: noqa: F401",
    "# pyright: reportUnusedImport=false",
)

#: The canonical scalars an annotation spells with their representative type
#: rather than with the canonical name, because the representative is the very
#: class of the value the engine returns. The builtins need no import.
REPRESENTATIVE_TYPES: Final = {
    "date": "Date",
    "time": "Time",
    "timestamp": "Timestamp",
    "uuid": "Uuid",
}

#: Decision 5 of ``DUCKDB_TYPE_IMPLEMENTATION_PLAN.md``: the whole representative
#: set is imported unconditionally by every generated file that declares anything,
#: because an un-imported annotation raises ``NameError`` while the class body
#: executes. Deriving the line from what a file annotates is what made it possible
#: to forget one.
REPRESENTATIVE_IMPORT: Final = (
    f"from kg_build_system.types import Array, {', '.join(sorted(set(REPRESENTATIVE_TYPES.values())))}"
)


def generation_fingerprint(request: DiscoveredGeneration, provider_version: str, dependency_content: tuple[bytes, ...]) -> str:
    normalized = {
        "configuration": request.request.configuration,
        "config_type": f"{request.request.config_module}.{request.request.config_qualname}",
        "format_version": FORMAT_VERSION,
        "provider": f"{request.request.provider_module}.{request.request.provider_qualname}",
        "provider_version": provider_version,
        "request_id": request.location.request_id,
        "request_source_package": request.location.source_package,
    }
    digest = sha256(json.dumps(normalized, sort_keys=True, separators=(",", ":")).encode())
    for content in dependency_content: digest.update(b"\0" + content)
    return digest.hexdigest()


def _safe_path(value: Path) -> PurePosixPath:
    path = PurePosixPath(value.as_posix())
    if path.is_absolute() or not path.parts or ".." in path.parts or path.suffix != ".py":
        raise GenerationError(f"invalid generated Python path {value}")
    return path


def _type_annotation(value: GeneratedType) -> str:
    if isinstance(value, GeneratedScalarType):
        return REPRESENTATIVE_TYPES.get(value.name, value.name)
    if isinstance(value, GeneratedStructType):
        return value.declaration_name
    if isinstance(value, GeneratedArrayType):
        return f"Array[{_type_annotation(value.item)}]"
    if isinstance(value, GeneratedNullableType):
        return f"{_type_annotation(value.value)} | None"
    raise TypeError(f"unsupported generated type {value!r}")


def _struct_references(value: GeneratedType) -> tuple[str, ...]:
    if isinstance(value, GeneratedStructType):
        return (value.declaration_name,)
    if isinstance(value, (GeneratedArrayType, GeneratedNullableType)):
        return _struct_references(value.item if isinstance(value, GeneratedArrayType) else value.value)
    return ()


def _field(field: GeneratedField) -> tuple[str, str]:
    annotation = f"Field[{_type_annotation(field.value_type)}]"
    arguments: list[str] = [f"name={field.external_name!r}"]
    if field.description is not None: arguments.append(f"description={field.description!r}")
    if field.annotations:
        arguments.append("annotations=(" + ", ".join(f"{a.class_name}(**{a.arguments!r})" for a in field.annotations) + ",)")
    return annotation, f"field({', '.join(arguments)})"


def _module_name(package_import: str, path: PurePosixPath) -> str:
    parts = path.with_suffix("").parts
    if parts[-1] == "__init__": parts = parts[:-1]
    return ".".join((package_import, *parts))


def _note_belongs_to_file(
    note: NullabilityNote, classes: tuple[GeneratedClass, ...],
) -> bool:
    """Whether one provenance line describes what this file declares.

    A catalogue rendered one file per table should carry only the line about that
    table's own source; a line naming no declaration is shared by the package.
    """
    if not note.declarations:
        return True
    declared = {declaration.name for declaration in classes}
    return bool(declared & set(note.declarations))


def render_package(request: DiscoveredGeneration, package: GeneratedPackage, fingerprint: str) -> dict[PurePosixPath, str]:
    paths: dict[str, PurePosixPath] = {}
    declarations: dict[str, tuple[PurePosixPath, GeneratedClass]] = {}
    normalized_files: list[tuple[PurePosixPath, GeneratedFile | None]] = []
    for file in package.files:
        path = _safe_path(file.relative_path)
        folded = path.as_posix().casefold()
        if folded in paths: raise GenerationError(f"case-normalized generated path collision: {path}")
        paths[folded] = path
        normalized_files.append((path, file))
        for declaration in file.declarations:
            if declaration.name in declarations: raise GenerationError(f"duplicate generated declaration identity {declaration.name}")
            declarations[declaration.name] = (path, declaration)
    # Every directory in a Python package is explicit and owned.
    required_initializers = {PurePosixPath("__init__.py")}
    for path, _file in normalized_files:
        parent = path.parent
        while parent != PurePosixPath("."):
            required_initializers.add(parent / "__init__.py")
            parent = parent.parent
    existing = {path for path, _ in normalized_files}
    normalized_files.extend((path, None) for path in sorted(required_initializers - existing, key=str))
    rendered: dict[PurePosixPath, str] = {}
    for path, file in sorted(normalized_files, key=lambda item: item[0].as_posix()):
        classes: tuple[GeneratedClass, ...] = () if file is None else file.declarations
        exports = () if file is None else file.exports
        imports: set[str] = set()
        if any(c.base == "Struct" for c in classes): imports.add("Struct")
        if any(c.base == "Table" for c in classes): imports.update(("Table", "TableOptions"))
        if any(c.base == "TableGroup" for c in classes): imports.update(("TableGroup", "TableGroupOptions"))
        fields = tuple(field for declaration in classes for field in declaration.fields)
        if fields: imports.update(("Field", "field"))
        cross: dict[str, set[str]] = {}
        for declaration in classes:
            references = [name for field in declaration.fields for name in _struct_references(field.value_type)]
            references += [member.declaration_name for member in declaration.members]
            for name in references:
                target = declarations.get(name)
                if target and target[0] != path:
                    cross.setdefault(_module_name(request.package_import, target[0]), set()).add(name)
        for name in exports:
            target = declarations.get(name)
            if target is None: raise GenerationError(f"generated export {name!r} has no declaration")
            if target[0] != path: cross.setdefault(_module_name(request.package_import, target[0]), set()).add(name)
        annotation_imports: dict[str, set[str]] = {}
        for declaration in classes:
            for field in declaration.fields:
                for annotation in field.annotations: annotation_imports.setdefault(annotation.import_module, set()).add(annotation.class_name)
        lines = [
            HEADER,
            f"# request: {request.location.request_id}",
            f"# fingerprint: {fingerprint}",
        ]
        lines.extend(f"# {note.line}" for note in package.nullability_notes
                     if _note_belongs_to_file(note, classes))
        lines.extend([*FILE_DIRECTIVES, ""])
        if classes:
            lines.append(f"from kg_build_system import {', '.join(sorted(imports))}")
            lines.append(REPRESENTATIVE_IMPORT)
        all_external = {module: set(names) for module, names in annotation_imports.items()}
        for module, names in cross.items(): all_external.setdefault(module, set()).update(names)
        lines.extend(f"from {module} import {', '.join(sorted(names))}" for module, names in sorted(all_external.items()))
        if classes or cross: lines.extend(("", ""))
        for index, declaration in enumerate(classes):
            base = f"({declaration.base})" if declaration.base else ""
            lines.append(f"class {declaration.name}{base}:")
            if declaration.description: lines.append(f"    {declaration.description!r}")
            if declaration.declaration_name is not None:
                options = "TableGroupOptions" if declaration.base == "TableGroup" else "TableOptions"
                lines.append(f"    options = {options}(name={declaration.declaration_name!r})")
            for field in declaration.fields:
                annotation, value = _field(field)
                lines.append(f"    {field.python_name}: {annotation} = {value}")
            for member in declaration.members: lines.append(f"    {member.python_name} = {member.declaration_name}")
            if not declaration.fields and not declaration.members and not declaration.description and declaration.declaration_name is None: lines.append("    pass")
            if index != len(classes) - 1: lines.extend(("", ""))
        if exports: lines.extend(("", f"__all__ = {list(exports)!r}"))
        content = "\n".join(lines).rstrip() + "\n"
        cst.parse_module(content)
        rendered[path] = content
    return rendered
