"""Deterministic Python sidecar rendering."""

from __future__ import annotations

from hashlib import sha256
import json
from pathlib import Path
from typing import Any

import libcst as cst

from .models import DiscoveredGeneration, GeneratedField, GeneratedFieldKind, GeneratedModule


FORMAT_VERSION = "1"


def generation_fingerprint(
    request: DiscoveredGeneration, provider_version: str, dependency_content: tuple[bytes, ...]
) -> str:
    normalized = {
        "class": request.location.class_name,
        "configuration": request.request.configuration,
        "config_type": f"{request.request.config_module}.{request.request.config_qualname}",
        "format_version": FORMAT_VERSION,
        "provider": f"{request.request.provider_module}.{request.request.provider_qualname}",
        "provider_version": provider_version,
    }
    digest = sha256()
    digest.update(json.dumps(normalized, sort_keys=True, separators=(",", ":")).encode())
    digest.update(b"\0")
    for content in dependency_content:
        digest.update(b"\0")
        digest.update(content)
    return digest.hexdigest()


def _literal(value: Any) -> str:
    return repr(value)


def _field(field: GeneratedField) -> tuple[str, str]:
    value_type = field.value_type
    if field.kind is GeneratedFieldKind.SCALAR:
        annotation = f"Field[{value_type}{' | None' if field.nullable else ''}]"
        factory = "field"
    elif field.kind is GeneratedFieldKind.STRUCT:
        annotation = f"StructField[{value_type}]"
        factory = "struct_field"
    else:
        item = f"{value_type}{' | None' if field.item_nullable else ''}"
        annotation = f"CollectionField[{item}]"
        factory = "collection_field"
    arguments: list[str] = []
    if field.external_name != field.python_name.rstrip("_"):
        arguments.append(f"name={field.external_name!r}")
    if field.description is not None:
        arguments.append(f"description={field.description!r}")
    if field.annotations:
        arguments.append("annotations=(" + ", ".join(
            f"{annotation.class_name}(**{_literal(annotation.arguments)})" for annotation in field.annotations
        ) + ",)")
    return annotation, f"{factory}({', '.join(arguments)})"


def render_sidecar(
    relative_source: Path,
    requests: tuple[DiscoveredGeneration, ...],
    modules: tuple[GeneratedModule, ...],
    fingerprints: tuple[str, ...],
) -> str:
    ownership = ", ".join(
        f"{request.location.class_name}:{fingerprint}" for request, fingerprint in zip(requests, fingerprints, strict=True)
    )
    all_classes = tuple(generated for module in modules for generated in module.classes)
    imports = {"CollectionField", "Field", "StructField", "collection_field", "field", "struct_field"}
    if any(generated.base == "Struct" for generated in all_classes):
        imports.add("Struct")
    annotation_imports: dict[str, set[str]] = {}
    for generated in all_classes:
        for field in generated.fields:
            for annotation in field.annotations:
                annotation_imports.setdefault(annotation.import_module, set()).add(annotation.class_name)
    lines = [
        "# Generated by kg-build-system. Do not edit manually.",
        f"# source: {relative_source.as_posix()}",
        f"# ownership: {ownership}",
        "",
        f"from kg_build_system import {', '.join(sorted(imports))}",
    ]
    lines.extend(
        f"from {module} import {', '.join(sorted(names))}"
        for module, names in sorted(annotation_imports.items())
    )
    lines.extend(("", ""))
    for index, generated in enumerate(all_classes):
        base = f"({generated.base})" if generated.base else ""
        lines.append(f"class {generated.name}{base}:")
        if generated.description:
            lines.append(f"    {_literal(generated.description)}")
        for field in generated.fields:
            annotation, declaration = _field(field)
            lines.append(f"    {field.python_name}: {annotation} = {declaration}")
        if not generated.fields and not generated.description:
            lines.append("    pass")
        if index != len(all_classes) - 1:
            lines.extend(("", ""))
    rendered = "\n".join(lines) + "\n"
    cst.parse_module(rendered)
    return rendered
