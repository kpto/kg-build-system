"""Desired-state computation and safe installation for edit-time generation."""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Iterable
import os
from pathlib import Path
import tempfile

import libcst as cst

from .discovery import discover, discover_file
from .models import DiscoveredGeneration, GenerationError, GenerationResult, GenerationStatus
from .providers import ProviderContext, get_provider
from .rendering import generation_fingerprint, render_sidecar


_HEADER = "# Generated by kg-build-system. Do not edit manually."


def _dotted(node: cst.BaseExpression | None) -> str | None:
    if isinstance(node, cst.Name):
        return node.value
    if isinstance(node, cst.Attribute):
        parent = _dotted(node.value)
        return f"{parent}.{node.attr.value}" if parent else None
    return None


class _WiringTransformer(cst.CSTTransformer):
    def __init__(self, requests: tuple[DiscoveredGeneration, ...], sidecar_module: str) -> None:
        self.requests = {request.location.class_name: request for request in requests}
        self.sidecar_module = sidecar_module
        self.imports: dict[str, str] = {}

    def visit_ImportFrom(self, node: cst.ImportFrom) -> None:
        if isinstance(node.names, cst.ImportStar):
            return
        module = _dotted(node.module) or ""
        dots = "." * len(node.relative)
        for alias in node.names:
            if not isinstance(alias, cst.ImportAlias):
                continue
            name = _dotted(alias.name)
            if name:
                imported_name = _dotted(alias.asname.name) if alias.asname else name
                if imported_name:
                    self.imports[imported_name] = dots + module

    def leave_ClassDef(
        self, original_node: cst.ClassDef, updated_node: cst.ClassDef
    ) -> cst.ClassDef | cst.FlattenSentinel[cst.BaseStatement]:
        request = self.requests.get(original_node.name.value)
        if request is None:
            return updated_node
        generated_name = request.generated_name
        imported_from = self.imports.get(generated_name)
        expected_module = f".{self.sidecar_module}"
        if imported_from is not None and imported_from != expected_module:
            raise GenerationError(
                f"{request.location.source_path}:{request.location.line}: {generated_name} is imported from {imported_from}, expected {expected_module}"
            )
        base_names = [_dotted(base.value) for base in updated_node.bases]
        generated_bases = [name for name in base_names if name and name.startswith("G_")]
        if len(generated_bases) > 1 or (generated_bases and generated_bases[0] != generated_name):
            raise GenerationError(
                f"{request.location.source_path}:{request.location.line}: conflicting generated class base"
            )
        if generated_name not in base_names:
            updated_node = updated_node.with_changes(
                bases=(cst.Arg(cst.Name(generated_name)), *updated_node.bases)
            )
        if imported_from == expected_module:
            return updated_node
        import_statement = cst.parse_statement(
            f"from {expected_module} import {generated_name}  # noqa: E402  # isort: skip\n\n"
        )
        if not isinstance(import_statement, cst.SimpleStatementLine):
            raise AssertionError("generated import did not parse as a simple statement")
        self.imports[generated_name] = expected_module
        return cst.FlattenSentinel((import_statement, updated_node))


def _wire(source: str, requests: tuple[DiscoveredGeneration, ...]) -> str:
    module = cst.parse_module(source)
    sidecar_module = f"_generated.{requests[0].sidecar_path.stem}"
    updated = module.visit(_WiringTransformer(requests, sidecar_module)).code
    cst.parse_module(updated)
    return updated


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def _generate_requests(
    root: Path, requests: tuple[DiscoveredGeneration, ...], *, check: bool = False,
) -> GenerationResult:
    by_source: dict[Path, list[DiscoveredGeneration]] = defaultdict(list)
    for request in requests:
        by_source[request.location.source_path].append(request)

    desired_sidecars: dict[Path, str] = {}
    desired_sources: dict[Path, str] = {}
    for source_path, source_requests_list in sorted(by_source.items()):
        source_requests = tuple(source_requests_list)
        sidecar_path = root / source_requests[0].sidecar_path
        modules = []
        fingerprints = []
        for request in source_requests:
            provider = get_provider(request.request.provider)
            context = ProviderContext(root, source_path, request.request)
            dependencies = provider.dependencies(context)
            modules.append(provider.generate(context, generated_name=request.generated_name))
            fingerprints.append(
                generation_fingerprint(
                    request,
                    provider.VERSION,
                    tuple(path.read_bytes() for path in dependencies),
                )
            )
        class_names = [generated.name for module in modules for generated in module.classes]
        if len(class_names) != len(set(class_names)):
            raise GenerationError(f"generated class name collision in {sidecar_path.relative_to(root)}")
        desired_sidecars[sidecar_path] = render_sidecar(
            source_path.relative_to(root), source_requests, tuple(modules), tuple(fingerprints)
        )
        desired_sources[source_path] = _wire(source_path.read_text(encoding="utf-8"), source_requests)

    desired: dict[Path, str] = {**desired_sidecars, **desired_sources}
    for sidecar in desired_sidecars:
        initializer = sidecar.parent / "__init__.py"
        desired.setdefault(initializer, "")
    changed = tuple(sorted(path.relative_to(root) for path, content in desired.items() if not path.exists() or path.read_text(encoding="utf-8") != content))
    if not changed:
        return GenerationResult(GenerationStatus.CURRENT)
    if check:
        diagnostics = tuple(f"{path.as_posix()} is missing or stale" for path in changed)
        return GenerationResult(GenerationStatus.STALE, diagnostics=diagnostics)

    for path in desired_sidecars:
        if path.exists() and not path.read_text(encoding="utf-8").startswith(_HEADER):
            raise GenerationError(f"refusing to overwrite unowned generated output {path}")
    # Sidecars are installed first so public modules never reference a missing generated module.
    for path in (*desired_sidecars, *(path for path in desired if path.name == "__init__.py"), *desired_sources):
        content = desired[path]
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            _atomic_write(path, content)
    # Recompute once to enforce idempotence of the installed desired state.
    if _generate_requests(root, requests, check=True).status is not GenerationStatus.CURRENT:
        raise GenerationError("generation did not produce an idempotent desired state")
    return GenerationResult(GenerationStatus.CHANGED, changed_paths=changed)


def generate(project_root: str | Path, *, check: bool = False) -> GenerationResult:
    """Generate or validate the complete deterministic desired state."""
    root = Path(project_root).resolve()
    return _generate_requests(root, discover(root), check=check)


class GenerationSession:
    """Stateful dependency index used for incremental watch-mode generation."""

    def __init__(self, project_root: str | Path) -> None:
        self.root = Path(project_root).resolve()
        self._by_source: dict[Path, tuple[DiscoveredGeneration, ...]] = {}
        self._by_dependency: dict[Path, set[Path]] = defaultdict(set)
        self._by_sidecar: dict[Path, Path] = {}

    def start(self) -> GenerationResult:
        """Establish a complete valid baseline and build the dependency index."""
        requests = discover(self.root)
        result = _generate_requests(self.root, requests)
        self._replace_index(requests)
        return result

    def _replace_index(self, requests: Iterable[DiscoveredGeneration]) -> None:
        by_source: dict[Path, list[DiscoveredGeneration]] = defaultdict(list)
        for request in requests:
            by_source[request.location.source_path].append(request)
        self._by_source = {path: tuple(values) for path, values in by_source.items()}
        self._rebuild_dependencies()

    def _rebuild_dependencies(self) -> None:
        self._by_dependency = defaultdict(set)
        self._by_sidecar = {}
        identities: set[tuple[Path, str]] = set()
        for source, requests in self._by_source.items():
            for request in requests:
                identity = (request.sidecar_path, request.generated_name)
                if identity in identities:
                    raise GenerationError(
                        f"generated output collision for {request.generated_name} in {request.sidecar_path}"
                    )
                identities.add(identity)
                context = ProviderContext(self.root, source, request.request)
                provider = get_provider(request.request.provider)
                for dependency in provider.dependencies(context):
                    self._by_dependency[dependency].add(source)
                self._by_sidecar[(self.root / request.sidecar_path).resolve()] = source

    def handle(self, changed_paths: Iterable[str | Path]) -> GenerationResult:
        """Regenerate only authored modules affected by one watched event batch."""
        affected: set[Path] = set()
        for changed in changed_paths:
            path = Path(changed)
            absolute = path.resolve() if path.is_absolute() else (self.root / path).resolve()
            if absolute.suffix == ".py":
                if absolute in self._by_sidecar:
                    continue
                if absolute.exists():
                    requests = discover_file(self.root, absolute)
                    if requests:
                        self._by_source[absolute] = requests
                        affected.add(absolute)
                    elif absolute in self._by_source:
                        del self._by_source[absolute]
                    self._rebuild_dependencies()
                elif absolute in self._by_source:
                    del self._by_source[absolute]
                    self._rebuild_dependencies()
                continue
            dependent_sources = self._by_dependency.get(absolute)
            if dependent_sources:
                affected.update(dependent_sources)
        requests = tuple(request for source in sorted(affected) for request in self._by_source.get(source, ()))
        if not requests:
            return GenerationResult(GenerationStatus.CURRENT)
        return _generate_requests(self.root, requests)
